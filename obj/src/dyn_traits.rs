//! Standard traits, made to work through a polymorphic handle.
//!
//! `Clone`, `PartialEq` and `Hash` are not object-safe: they mention `Self` in argument or return
//! position, so `dyn ShapeDyn: Clone` can never hold. This module carries the object-safe shims
//! that stand in for them, and `#[obj::class(dyn_traits(..))]` generates the impls.
//!
//! `Debug` and `Display` need no shim — they are object-safe already, so the attribute simply adds
//! them as supertraits of the class's interface, which is what makes every subclass provide them.
//!
//! You do not implement these by hand. Opt in on the class:
//!
//! ```ignore
//! #[obj::class(abstract, dyn_traits(Debug, Clone, PartialEq, Hash))]
//! #[derive(Debug, Clone, PartialEq, Hash)]
//! pub struct Shape { pub x: i32 }
//! ```
//!
//! and every class in the hierarchy gains the corresponding impl on [`Obj`](crate::Obj) and the
//! other handles.

use core::any::Any;
use core::hash::Hasher;

use crate::class::AnyObj;

/// A class whose objects can be deep-copied through a polymorphic handle.
///
/// This is the `obj` analogue of the C++ "virtual clone" (prototype) idiom: the copy is of the
/// **most-derived** class, whatever class the handle is typed with. Cloning an `Obj<Shape>` that
/// happens to hold a `Circle` yields an `Obj<Shape>` holding a `Circle`.
///
/// Generated by `#[obj::class(dyn_traits(Clone))]`, which requires the class itself to implement
/// [`Clone`].
///
/// # Safety
///
/// [`clone_raw`](Self::clone_raw) must return `Box::into_raw(Box::new(c))` for a `c` of the same
/// most-derived type as `self`. Handles pair that pointer with `self`'s own vtable, so a clone of
/// any other type would hand `Box` the wrong size, alignment and drop glue.
pub unsafe trait CloneObj: AnyObj {
    /// Deep-copies the complete object into a fresh allocation.
    ///
    /// Returns the pointer from `Box::into_raw`, since the concrete type cannot be named here.
    /// The caller owns the allocation and must rebuild a `Box` over it to free it.
    fn clone_raw(&self) -> *mut u8;
}

/// A class whose objects can be compared through a polymorphic handle.
///
/// Comparison is *heterogeneous*: two objects are equal only when their most-derived classes match
/// and the underlying values compare equal. A `Circle` never equals a `Square`, even through an
/// `Obj<Shape>` on both sides.
///
/// Generated by `#[obj::class(dyn_traits(PartialEq))]`, which requires the class to implement
/// [`PartialEq`].
pub trait DynEq {
    /// Views the complete object as [`Any`], so the other side can recover its concrete type.
    fn as_any(&self) -> &dyn Any;

    /// Compares against another object's [`Any`] view, returning `false` if the classes differ.
    fn dyn_eq(&self, other: &dyn Any) -> bool;
}

/// A class whose objects are totally ordered by equality — the [`Eq`] counterpart to [`DynEq`].
///
/// A marker, generated by `#[obj::class(dyn_traits(Eq))]`; it is what lets a handle implement
/// [`Eq`] and so be used as a `HashMap` key.
pub trait DynTotalEq: DynEq {}

/// A class whose objects can be hashed through a polymorphic handle.
///
/// The most-derived class's identity is folded into the hash before the value itself, so two
/// objects of different classes hash differently even when their fields agree — matching the
/// equality rule in [`DynEq`].
///
/// Generated by `#[obj::class(dyn_traits(Hash))]`, which requires the class to implement [`Hash`].
///
/// [`Hash`]: core::hash::Hash
pub trait DynHash {
    /// Feeds the class identity and then the value into `state`.
    fn dyn_hash(&self, state: &mut dyn Hasher);
}
